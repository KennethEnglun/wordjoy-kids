import { chromium } from 'playwright'
import { mkdir } from 'fs/promises'

await mkdir('screenshots', { recursive: true })
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://127.0.0.1:4173/')
await page.waitForTimeout(500)
await page.screenshot({ path: 'screenshots/shot_wj_r5_home.png', fullPage: false })
await page.getByRole('button', { name: '冒險', exact: true }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: 'screenshots/shot_wj_r5_adventure.png', fullPage: false })
await page.getByRole('button', { name: '任務', exact: true }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: 'screenshots/shot_wj_r5_tasks.png', fullPage: false })
await page.getByRole('button', { name: '商店', exact: true }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: 'screenshots/shot_wj_r5_shop.png', fullPage: false })
await page.getByRole('button', { name: '角色', exact: true }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: 'screenshots/shot_wj_r5_character.png', fullPage: false })
await page.goto('http://127.0.0.1:4173/#/adventure/prek')
await page.waitForTimeout(300)
await page.getByRole('button', { name: /對對碰/ }).click()
await page.getByRole('button', { name: /我同家人|Family/i }).first().click()
await page.waitForTimeout(500)
await page.screenshot({ path: 'screenshots/shot_wj_r5_play.png', fullPage: false })
await browser.close()
console.log('shots ok')
